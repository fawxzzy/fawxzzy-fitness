// Derives the inline app-loader icon (docs/design-system/LOADER-SPEC.md) from the ONE Fitness app image.
//
// Source of truth: public/app/icon-512.png. It is byte-identical to the image the FawxzzyWeb site shows for
// Fitness (FawxzzyWeb public/apps/fitness/icon.png, catalog key `icon` for slug `fitness`, SHA-256 below),
// and it is itself derived from public/brand/fitness-app-icon-source.jpg by scripts/generate-icons.mjs.
//
// Output: src/lib/app-loader-icon.ts, a 256 px lossy WebP (quality 80) inlined as a data URI so the loader
// never waits on a request (no pop-in, no layout jump). No network, no browser.
//
//   node scripts/generate-app-loader-icon.mjs          write the file
//   node scripts/generate-app-loader-icon.mjs --check  exit 1 if the committed file differs from a fresh derivation
import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_PATH = path.join(rootDir, "public", "app", "icon-512.png");
const OUTPUT_PATH = path.join(rootDir, "src", "lib", "app-loader-icon.ts");
const SOURCE_SHA256 = "5F1011EF2DB7A4725E991D5FB6347F3E589028669F74BC35F273E6E800F11F03";
const ICON_PX = 256;
const WEBP_QUALITY = 80;

const sha256 = (buffer) => crypto.createHash("sha256").update(buffer).digest("hex").toUpperCase();

async function derive() {
  const source = await fs.readFile(SOURCE_PATH);
  if (sha256(source) !== SOURCE_SHA256) {
    throw new Error(`public/app/icon-512.png is not the site's Fitness app image (expected SHA-256 ${SOURCE_SHA256}, got ${sha256(source)}).`);
  }
  const { default: sharp } = await import("sharp");
  const webp = await sharp(source).resize(ICON_PX, ICON_PX, { fit: "cover" }).webp({ quality: WEBP_QUALITY }).toBuffer();
  return `// GENERATED by scripts/generate-app-loader-icon.mjs from public/app/icon-512.png. Do not edit by hand.
// Source SHA-256 ${SOURCE_SHA256}; ${ICON_PX} px lossy WebP (quality ${WEBP_QUALITY}), ${webp.length} bytes, SHA-256 ${sha256(webp)}.
export const APP_LOADER_ICON_SOURCE_SHA256 = "${SOURCE_SHA256}";
export const APP_LOADER_ICON_PX = ${ICON_PX};
export const APP_LOADER_ICON_BYTES = ${webp.length};
export const APP_LOADER_ICON_SHA256 = "${sha256(webp)}";
export const APP_LOADER_ICON_DATA_URI =
  "data:image/webp;base64,${webp.toString("base64")}";
`;
}

const next = await derive();
if (process.argv.includes("--check")) {
  const current = await fs.readFile(OUTPUT_PATH, "utf8").catch(() => "");
  if (current !== next) {
    console.error("src/lib/app-loader-icon.ts is stale: run node scripts/generate-app-loader-icon.mjs");
    process.exit(1);
  }
  console.log("ok    src/lib/app-loader-icon.ts");
} else {
  await fs.writeFile(OUTPUT_PATH, next);
  console.log(`sync  src/lib/app-loader-icon.ts (${next.length} chars)`);
}
