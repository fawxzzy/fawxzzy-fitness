export function getWritableProgressionScenarioDefinition(id) {
  return getWritableProgressionScenarioDefinitions().find((scenario) => scenario.id === id) ?? null;
}

export function listWritableProgressionScenarioSummaries() {
  return getWritableProgressionScenarioDefinitions().map((scenario) => ({
    id: scenario.id,
    title: scenario.title,
    expected: scenario.expected,
    category: scenario.category ?? "progression_case",
    prefix: scenario.prefix ?? PROGRESSION_QA_PREFIX,
    expectations: scenario.expectations ?? null,
  }));
}

export function assertWritableProgressionScenarioId(id) {
  if (!ALL_WRITABLE_SCENARIO_IDS.includes(id)) {
    throw new Error(`Unknown progression QA scenario: ${id}. Expected one of: ${ALL_WRITABLE_SCENARIO_IDS.join(", ")}`);
  }
}
