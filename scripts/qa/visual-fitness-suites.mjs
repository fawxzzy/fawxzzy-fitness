export function listVisualFitnessSuites({ proofLane = null } = {}) {
  return Object.values(VISUAL_FITNESS_SUITES).filter((suite) => {
    if (!proofLane) {
      return true;
    }

    return suite.proofLane === proofLane;
  });
}

export function getVisualFitnessSuite(name) {
  return VISUAL_FITNESS_SUITES[name] ?? null;
}
